  const { base, subnets, failures, free, summary } = plan

  const subnetRows = subnets
    .map(
      (s) => `<tr>
        <td><span class="swatch" style="background:${escapeHtml(s.color || '#38bdf8')}"></span>${escapeHtml(s.name || `Subnet ${s.step}`)}</td>
        <td class="num">${formatCount(s.hosts)}</td>
        <td class="mono">/${s.prefix} · ${escapeHtml(s.mask)}</td>
        <td class="mono">${escapeHtml(s.network)}</td>
        <td class="mono">${escapeHtml(s.first)} – ${escapeHtml(s.last)}</td>
        <td class="mono">${escapeHtml(s.gateway || '—')}</td>
        <td class="mono">${s.hasBroadcast ? escapeHtml(s.broadcast) : `<em>${escapeHtml(text.p2pNote)}</em>`}</td>
        <td class="num">${formatCount(s.usable)}</td>
        <td class="num">${Math.round(s.efficiency)}%</td>
      </tr>`,
    )
    .join('')

