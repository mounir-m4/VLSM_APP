/** Open the print dialog with the report; user saves as PDF. Returns 'print' | 'download' | null. */
export function exportPlanPdf(plan, lang = 'en') {
  const html = buildReportHtml(plan, lang)
  const blob = new Blob([html], { type: 'text/html;charset=utf-8' })
  const url = URL.createObjectURL(blob)

  let win = null
  try {
    win = window.open(url, '_blank')
  } catch {
    win = null
  }

  if (win) {
    URL.revokeObjectURL(url)
    const trigger = () => {
      try {
        win.focus()
        win.print()
      } catch {
        /* user can print manually */
      }
    }
    if (win.document?.readyState === 'complete') trigger()
    else win.addEventListener?.('load', trigger, { once: true })
    return 'print'
  }

  // Popup blocked: download the HTML report instead.
  const anchor = document.createElement('a')
  anchor.href = url
  anchor.download = `vlsm-report-${plan.base.network.replaceAll('.', '-')}-${plan.base.prefix}.html`
  document.body.appendChild(anchor)
  anchor.click()
  anchor.remove()
  URL.revokeObjectURL(url)
  return 'download'
}
